import assert from "node:assert/strict";
import { chromium } from "playwright";
const arg = (name, fallback) => process.argv.find((v) => v.startsWith(`--${name}=`))?.slice(name.length + 3) ?? fallback;
const browserPath = arg("browser-executable", undefined);
const base = arg("base-url", "http://localhost:3100");
const browser = await chromium.launch(browserPath ? { executablePath: browserPath } : {});
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
try {
  await page.goto(`${base}/experiments/failure-recovery`);
  await page.getByText("Simulate retry failure", { exact: true }).click();
  await page.getByText("Retry needs confirmation", { exact: true }).click();
  await page.getByRole("button", { name: "Start export" }).focus();
  await page.keyboard.press("Enter");
  await page.getByText("Export needs attention", { exact: true }).waitFor();
  assert.equal(await page.locator('.fr-steps li[data-status="complete"]').count(), 3);
  assert.equal(await page.locator('.fr-steps li[data-status="failed"]').count(), 1);
  assert.match(await page.locator(".fr-preserved").innerText(), /Earlier steps remain complete/);
  await page.getByRole("button", { name: "Retry Upload archive" }).click();
  assert.equal(await page.getByRole("button", { name: "Confirm retry" }).count(), 1);
  assert.equal(await page.locator('.fr-steps li[data-status="failed"]').count(), 1);
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  assert.equal(await page.locator('.fr-steps li[data-status="failed"]').count(), 1);
  await page.getByRole("button", { name: "Retry Upload archive" }).click();
  await page.getByRole("button", { name: "Confirm retry" }).click();
  await page.getByText("Export needs attention", { exact: true }).waitFor();
  assert.equal(await page.locator('.fr-steps li[data-status="complete"]').count(), 3);
  await page.getByText("Simulate retry failure", { exact: true }).click();
  await page.getByRole("button", { name: "Retry Upload archive" }).click();
  await page.getByRole("button", { name: "Confirm retry" }).click();
  await page.getByText("Export complete", { exact: true }).waitFor();
  assert.equal(await page.locator('.fr-steps li[data-status="complete"]').count(), 5);
  await page.getByRole("button", { name: "Start another sample" }).click();
  await page.getByText("Rollback available", { exact: true }).click();
  await page.getByRole("button", { name: "Start export" }).click();
  await page.getByText("Export needs attention", { exact: true }).waitFor();
  assert.match(await page.locator(".fr-actions").innerText(), /Rollback unavailable/);
  await page.getByText("Rollback available", { exact: true }).click();
  await page.getByRole("button", { name: "Roll back" }).click();
  await page.getByText("Rollback complete", { exact: true }).waitFor();
  assert.equal(await page.locator('.fr-steps li[data-status="rolled-back"]').count(), 3);
  await page.getByRole("button", { name: "Start another sample" }).click();
  await page.getByRole("button", { name: "None", exact: true }).click();
  await page.getByRole("button", { name: "Start export" }).click();
  await page.getByText("Export complete", { exact: true }).waitFor();
  assert.equal(await page.locator('.fr-steps li[data-status="complete"]').count(), 5);
  console.log("Failure Recovery interaction checks passed");
} finally { await browser.close(); }
